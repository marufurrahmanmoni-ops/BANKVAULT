// Release signing is read from keystore.properties (git-ignored). Never commit keys.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use(::load)
}

android {
    namespace = "com.bankvault"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.bankvault"
        // Android 14 (API 34) minimum: matches the target devices and lets us rely on
        // Ed25519/ECDSA providers, setPackagesSuspended, specialUse FGS type and modern BAL rules.
        minSdk = 34
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        // Threat feed is OFF until the owner configures a URL in Settings.
        buildConfigField("String", "DEFAULT_FEED_URL", "\"\"")
        // Public (verification-only) key of the threat-feed publisher. Replace with your own,
        // generated by tools/feed-signer. Private keys never go into the APK.
        buildConfigField("String", "FEED_PUBLIC_KEY_ID", "\"bv-feed-1\"")
        buildConfigField("String", "FEED_PUBLIC_KEY_X509_B64", "\"\"")
    }

    signingConfigs {
        if (keystoreProps.containsKey("storeFile")) {
            create("release") {
                storeFile = file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            isDebuggable = true
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    packaging {
        resources.excludes += setOf("/META-INF/{AL2.0,LGPL2.1}", "META-INF/versions/9/OSGI-INF/MANIFEST.MF")
    }
}

